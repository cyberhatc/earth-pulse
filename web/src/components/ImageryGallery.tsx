import type { PlacePayload } from '../types/payload'
import { apiUrl } from '../lib/api'
import ScenarioStatus from './ScenarioStatus'

interface Props {
  payload: PlacePayload
  lowBandwidth: boolean
  offline?: boolean
}

export default function ImageryGallery({ payload, lowBandwidth, offline = false }: Props) {
  const past = payload.past.imagery ?? []
  const projected = payload.forecast.projected_images ?? []
  const projectedAll = projected.some((p) => p.date === '2030')
    ? projected
    : [
        ...projected,
        {
          date: '2030',
          parameter: 'temperature',
          url: '/imagery/projected?parameter=temperature&year=2030',
          label: 'Model-projected (Theil-Sen extrapolation) - not an observation',
        },
      ]

  if (lowBandwidth) {
    return (
      <div className="card">
        <h3>Imagery (low-bandwidth mode)</h3>
        <p className="imagery-note">Imagery hidden to save bandwidth. Toggle low-bandwidth off to load NASA GIBS tiles.</p>
      </div>
    )
  }

  const observedCount = past.length
  const projectedCount = projectedAll.length

  return (
    <div className="card imagery-card">
      {/* ---- Header with icon ---- */}
      <div className="imagery-section-header">
        <svg className="imagery-section-icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
          <path d="M23 19a2 2 0 0 1-2 2H3a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h4l2-3h6l2 3h4a2 2 0 0 1 2 2z"/>
          <circle cx="12" cy="13" r="4"/>
        </svg>
        <h3>Imagery — past, present &amp; projected</h3>
      </div>

      {/* ---- Timeline bar ---- */}
      <div className="imagery-timeline" aria-hidden="true">
        <span className="imagery-timeline-dot observed" title="Observed" />
        <div className="imagery-timeline-line" />
        <span className="imagery-timeline-label">2000 → today</span>
        <div className="imagery-timeline-line" />
        <span className="imagery-timeline-dot projected" title="Projected" />
      </div>

      {/* ---- Count badge ---- */}
      <div className="imagery-count">
        <b>{observedCount}</b> observed tiles · <b>{projectedCount}</b> projected maps
      </div>

      {/* ---- Observed tiles ---- */}
      <div className="badge-row" style={{ marginBottom: 8 }}><span className="tag observed">Observed (map tiles)</span></div>
      {past.length === 0 && <p className="imagery-note">No GIBS thumbnails available for this point.</p>}
      <div className="imagery-grid">
        {past.map((img, i) => (
          <figure className="imagery-item" key={img.url} style={{ animationDelay: `${i * 0.04}s` }}>
            <span className="year-badge">{img.date.slice(0, 4)}</span>
            <span className="layer-label">{img.layer}</span>
            <img
              src={img.url}
              loading="lazy"
              alt={`${img.layer} over selected location on ${img.date}`}
              onError={(e) => { (e.target as HTMLImageElement).style.visibility = 'hidden' }}
            />
            <figcaption>{img.layer.replace(/_/g, ' ')} · {img.date}</figcaption>
          </figure>
        ))}
      </div>
      <a className="btn-link" href="https://earthexplorer.usgs.gov/?searchType=specificPlace#results" target="_blank" rel="noreferrer">
        Open USGS EarthExplorer (Landsat scenes) for this point →
      </a>

      {/* ---- Model-projected ---- */}
      <div className="badge-row" style={{ margin: '12px 0 8px' }}><span className="tag forecast">Model-projected</span></div>
      {offline ? (
        <p className="imagery-note">Projected SVG maps are generated by the live API and are not available in offline sample mode.</p>
      ) : (
        <>
          <div className="imagery-grid">
            {projectedAll.map((img, i) => (
              <figure className="imagery-item" key={img.url} style={{ animationDelay: `${(past.length + i) * 0.04}s` }}>
                <span className="year-badge">{img.date}</span>
                <span className="layer-label">{img.parameter}</span>
                <img src={apiUrl(img.url)} loading="lazy" alt={img.label} />
                <figcaption>{img.parameter} · {img.date} · model projection</figcaption>
              </figure>
            ))}
          </div>
          <p className="imagery-note" style={{ marginTop: 6 }}>Projected maps extrapolate the fitted trend — not observations and not a guaranteed future.</p>
        </>
      )}

      {/* ---- AI scenario ---- */}
      <div className="badge-row" style={{ margin: '12px 0 8px' }}><span className="tag scenario">AI-generated scenario</span></div>
      <ScenarioStatus payload={payload} />
    </div>
  )
}